-- C3 Site Finder: shared methodology editing, step B of 3. Run as c3_migrator (owner of the c3 tables) with
-- "NJTruckCharging.CloudCopy methodology-editing". Idempotent: safe to run again. ADDITIVE ONLY - no column, row or
-- table is removed or rewritten.
--
-- 1. Schema: audit columns on MethodologyVersions / MethodologyActivations and the append-only MethodologyChangeLog
--    (identical to the EF migration AddMethodologyEditingAudit and to sql/02-c3-tables.sql).
-- 2. c3_methodology_writer gets EXACTLY what Apply Scoring / Restore / drafts need, nothing else:
--      MethodologyVersions    SELECT, INSERT, DELETE (drafts only), UPDATE of the mutable columns only
--      SiteVersionScores      SELECT, INSERT, DELETE                     (proposed scores)
--      MethodologyState       SELECT, UPDATE of the active-version pointer only
--      MethodologyActivations SELECT, INSERT                             (append-only history)
--      MethodologyChangeLog   SELECT, INSERT                             (append-only audit)
--      CandidateSites         SELECT, UPDATE of the score columns only   (never addresses, acreage, owner data, ...)
--    No access to any other table (saved sites, contacts, research, screening, feasibility, custom fields, ...).
-- 3. A trigger makes published and baseline versions immutable for the writer (rules, name, status), and refuses
--    deleting them, whatever the API does. Row-level security policies scope every permission to the writer.
-- 4. c3_runtime_readonly keeps SELECT only (now also on the new audit table).

-- ---- 1. schema -------------------------------------------------------------------------------------------------
ALTER TABLE c3."MethodologyVersions"
    ADD COLUMN IF NOT EXISTS "Revision" integer NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "CreatedByUserId" character varying(64),
    ADD COLUMN IF NOT EXISTS "CreatedByEmail" character varying(320),
    ADD COLUMN IF NOT EXISTS "UpdatedByUserId" character varying(64),
    ADD COLUMN IF NOT EXISTS "UpdatedByEmail" character varying(320),
    ADD COLUMN IF NOT EXISTS "PublishedByUserId" character varying(64),
    ADD COLUMN IF NOT EXISTS "PublishedByEmail" character varying(320);
ALTER TABLE c3."MethodologyVersions" ALTER COLUMN "Revision" DROP DEFAULT;   -- same as the EF model (value always sent)

ALTER TABLE c3."MethodologyActivations"
    ADD COLUMN IF NOT EXISTS "ActorUserId" character varying(64),
    ADD COLUMN IF NOT EXISTS "ActorEmail" character varying(320);

CREATE TABLE IF NOT EXISTS c3."MethodologyChangeLog" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "VersionId" integer NOT NULL,
    "VersionName" character varying(120) NOT NULL,
    "Action" character varying(20) NOT NULL,
    "AtUtc" timestamp with time zone NOT NULL,
    "ActorUserId" character varying(64),
    "ActorEmail" character varying(320),
    "RevisionBefore" integer,
    "RevisionAfter" integer,
    "RulesHashBefore" character varying(64),
    "RulesHashAfter" character varying(64),
    "PreviousActiveVersionId" integer,
    "ChangesJson" text,
    "BeforeJson" text,
    "AfterJson" text,
    "Note" character varying(1000),
    CONSTRAINT "PK_MethodologyChangeLog" PRIMARY KEY ("Id")

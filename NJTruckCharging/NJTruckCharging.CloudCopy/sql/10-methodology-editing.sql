CREATE INDEX IF NOT EXISTS "IX_MethodologyChangeLog_AtUtc" ON c3."MethodologyChangeLog" ("AtUtc");
CREATE INDEX IF NOT EXISTS "IX_MethodologyChangeLog_VersionId_AtUtc" ON c3."MethodologyChangeLog" ("VersionId", "AtUtc");

-- ---- 3. immutability guard (applies to the writer only; the owner's data refresh is unaffected) ---------------
CREATE OR REPLACE FUNCTION c3.c3_methodology_version_guard() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
BEGIN
  IF current_user <> 'c3_methodology_writer' THEN
    RETURN COALESCE(NEW, OLD);
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW."IsBaseline" OR NEW."Status" <> 'Draft' THEN
      RAISE EXCEPTION 'c3: new methodology versions must be drafts' USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
  ELSIF TG_OP = 'DELETE' THEN
    IF OLD."IsBaseline" OR OLD."Status" <> 'Draft' THEN
      RAISE EXCEPTION 'c3: published and baseline methodology versions are permanent' USING ERRCODE = '42501';
    END IF;
    RETURN OLD;
  END IF;
  -- UPDATE
  IF NEW."IsBaseline" IS DISTINCT FROM OLD."IsBaseline" THEN
    RAISE EXCEPTION 'c3: the baseline flag cannot change' USING ERRCODE = '42501';
  END IF;
  IF OLD."Status" = 'Published' AND (NEW."Status" <> 'Published'
      OR NEW."RulesJson" IS DISTINCT FROM OLD."RulesJson" OR NEW."RulesHash" IS DISTINCT FROM OLD."RulesHash"
      OR NEW."Name" IS DISTINCT FROM OLD."Name" OR NEW."ChangeSummary" IS DISTINCT FROM OLD."ChangeSummary"
      OR NEW."PublishedAtUtc" IS DISTINCT FROM OLD."PublishedAtUtc") THEN
    RAISE EXCEPTION 'c3: published methodology versions are immutable' USING ERRCODE = '42501';
  END IF;
  IF NEW."Status" NOT IN ('Draft', 'Published') THEN
    RAISE EXCEPTION 'c3: invalid methodology status' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION c3.c3_methodology_version_guard() FROM PUBLIC;
DROP TRIGGER IF EXISTS c3_methodology_version_guard ON c3."MethodologyVersions";
CREATE TRIGGER c3_methodology_version_guard BEFORE INSERT OR UPDATE OR DELETE ON c3."MethodologyVersions"
    FOR EACH ROW EXECUTE FUNCTION c3.c3_methodology_version_guard();

-- ---- 2. writer permissions (revoke everything first, so a re-run converges to exactly this set) -----------------
DO $$
DECLARE t record;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'c3_methodology_writer') THEN
    RAISE EXCEPTION 'Role c3_methodology_writer does not exist: run 09-methodology-writer-role.sql (writer-bootstrap-sql) first.';
  END IF;
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'c3' LOOP
    EXECUTE format('REVOKE ALL ON c3.%I FROM c3_methodology_writer', t.tablename);
    EXECUTE format('DROP POLICY IF EXISTS c3_methodology_writer_select ON c3.%I', t.tablename);
    EXECUTE format('DROP POLICY IF EXISTS c3_methodology_writer_insert ON c3.%I', t.tablename);
    EXECUTE format('DROP POLICY IF EXISTS c3_methodology_writer_update ON c3.%I', t.tablename);
    EXECUTE format('DROP POLICY IF EXISTS c3_methodology_writer_delete ON c3.%I', t.tablename);
  END LOOP;
END $$;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA c3 FROM c3_methodology_writer;

GRANT SELECT, INSERT, DELETE ON c3."MethodologyVersions" TO c3_methodology_writer;
GRANT UPDATE ("Name", "Status", "RulesJson", "RulesHash", "ChangeSummary", "UpdatedAtUtc", "PublishedAtUtc",
              "PreviewRulesHash", "ScoresDataVersion", "PreviewedAtUtc", "PreviewSummaryJson", "Revision",
              "UpdatedByUserId", "UpdatedByEmail", "PublishedByUserId", "PublishedByEmail")
    ON c3."MethodologyVersions" TO c3_methodology_writer;
GRANT SELECT, INSERT, DELETE ON c3."SiteVersionScores" TO c3_methodology_writer;
GRANT SELECT ON c3."MethodologyState" TO c3_methodology_writer;
GRANT UPDATE ("ActiveVersionId", "PreviousActiveVersionId", "ActivatedAtUtc") ON c3."MethodologyState" TO c3_methodology_writer;
GRANT SELECT, INSERT ON c3."MethodologyActivations" TO c3_methodology_writer;
GRANT SELECT, INSERT ON c3."MethodologyChangeLog" TO c3_methodology_writer;
GRANT SELECT ON c3."CandidateSites" TO c3_methodology_writer;
DO $$
DECLARE cols text;
BEGIN
  -- "Score", "ComputedRank", "TruckDemandPoints", "ScoreVersionId" and every "Breakdown_*" column; nothing else.
  SELECT string_agg(format('%I', column_name), ', ' ORDER BY ordinal_position) INTO cols
  FROM information_schema.columns
  WHERE table_schema = 'c3' AND table_name = 'CandidateSites'
    AND (column_name IN ('Score', 'ComputedRank', 'TruckDemandPoints', 'ScoreVersionId') OR column_name LIKE 'Breakdown\_%');
  EXECUTE format('GRANT UPDATE (%s) ON c3."CandidateSites" TO c3_methodology_writer', cols);
END $$;

-- Row-level security (already enabled on every c3 table): policies for the writer only.
ALTER TABLE c3."MethodologyChangeLog" ENABLE ROW LEVEL SECURITY;
CREATE POLICY c3_methodology_writer_select ON c3."MethodologyVersions" FOR SELECT TO c3_methodology_writer USING (true);
CREATE POLICY c3_methodology_writer_insert ON c3."MethodologyVersions" FOR INSERT TO c3_methodology_writer
    WITH CHECK (NOT "IsBaseline" AND "Status" = 'Draft');
CREATE POLICY c3_methodology_writer_update ON c3."MethodologyVersions" FOR UPDATE TO c3_methodology_writer USING (true) WITH CHECK (true);
CREATE POLICY c3_methodology_writer_delete ON c3."MethodologyVersions" FOR DELETE TO c3_methodology_writer
    USING ("Status" = 'Draft' AND NOT "IsBaseline");
CREATE POLICY c3_methodology_writer_select ON c3."SiteVersionScores" FOR SELECT TO c3_methodology_writer USING (true);
CREATE POLICY c3_methodology_writer_insert ON c3."SiteVersionScores" FOR INSERT TO c3_methodology_writer WITH CHECK (true);
CREATE POLICY c3_methodology_writer_delete ON c3."SiteVersionScores" FOR DELETE TO c3_methodology_writer USING (true);
CREATE POLICY c3_methodology_writer_select ON c3."MethodologyState" FOR SELECT TO c3_methodology_writer USING (true);
CREATE POLICY c3_methodology_writer_update ON c3."MethodologyState" FOR UPDATE TO c3_methodology_writer
    USING ("Id" = 1) WITH CHECK ("Id" = 1);
CREATE POLICY c3_methodology_writer_select ON c3."MethodologyActivations" FOR SELECT TO c3_methodology_writer USING (true);
CREATE POLICY c3_methodology_writer_insert ON c3."MethodologyActivations" FOR INSERT TO c3_methodology_writer WITH CHECK (true);
CREATE POLICY c3_methodology_writer_select ON c3."MethodologyChangeLog" FOR SELECT TO c3_methodology_writer USING (true);
CREATE POLICY c3_methodology_writer_insert ON c3."MethodologyChangeLog" FOR INSERT TO c3_methodology_writer WITH CHECK (true);
CREATE POLICY c3_methodology_writer_select ON c3."CandidateSites" FOR SELECT TO c3_methodology_writer USING (true);
CREATE POLICY c3_methodology_writer_update ON c3."CandidateSites" FOR UPDATE TO c3_methodology_writer USING (true) WITH CHECK (true);

-- ---- 4. read-only runtime role: SELECT on the new audit table, like every other c3 table -------------------------
REVOKE ALL ON c3."MethodologyChangeLog" FROM PUBLIC;
GRANT SELECT ON c3."MethodologyChangeLog" TO c3_runtime_readonly;
DROP POLICY IF EXISTS c3_runtime_read ON c3."MethodologyChangeLog";
CREATE POLICY c3_runtime_read ON c3."MethodologyChangeLog" FOR SELECT TO c3_runtime_readonly USING (true);
DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated', 'service_role', 'authenticator') LOOP
    EXECUTE format('REVOKE ALL ON c3."MethodologyChangeLog" FROM %I', r.rolname);
  END LOOP;
END $$;
